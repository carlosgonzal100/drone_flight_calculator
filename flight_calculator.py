def flight_time_table(max_weight_grams, step_grams):
    """returns a list of (weight, flight_time) pairs for payload weights from 0 to including
    the max weight of the payload, in increments of step_grams.
    
    Arguments:
        max_weight_grams: The maximum weight in grams.
        step_grams: amount of grams being incremented for each entry.
        
    Returns:
        table: a list of (weight, flight_time) pairs"""
    
    table = []
    for weight in range(0, max_weight_grams + 1, step_grams):
        flight_time = calculate_flight_time(weight)
        table.append((weight, flight_time))
    return table

