def calculate_flight_time(weight_grams):
    """Calculates active flight time in minuits for a given payload weight in grams
    
    Arguments:
        weight_grams: The added weight in grams.

    Returns:
        flight_time: the estimated flight time in minuits
    
    """

    if weight_grams < 0:
        raise ValueError("Weight must be greater than or equal to 0 grams.")

    #EDIT -- copilot suggested a random formula here instead of the one provided in the prompt,
    #so i had to correct and edit it myself.
    flight_time = 180 - 0.1 * weight_grams
    return max(0, flight_time)


